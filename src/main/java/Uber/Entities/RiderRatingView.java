package Uber.Entities;

public class RiderRatingView {
    Integer rideId;
    Double rideRating;
    Double riderRating;

    @Override
    public String toString() {
        return "RiderRatingView{" +
                "rideId='" + rideId + '\'' +
                ", rideRating=" + rideRating +
                ", riderRating=" + riderRating +
                '}';
    }

    public RiderRatingView(Integer rideId, Double rideRating, Double riderRating) {
        this.rideId = rideId;
        this.rideRating = rideRating;
        this.riderRating = riderRating;
    }
}
